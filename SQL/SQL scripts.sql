-- Customers with more than one distinct street on file: customer attributes are not
-- strictly 1:1 with CUSTOMER_ID, so DIM_CUSTOMER below picks the address from the
-- customer's most recent order rather than an arbitrary row.
SELECT CUSTOMER_ID, COUNT(DISTINCT CUSTOMER_STREET) AS ADDRESS_COUNT
FROM TRANSFORMED.STG_ORDERS
GROUP BY CUSTOMER_ID
HAVING COUNT(DISTINCT CUSTOMER_STREET) > 1;

