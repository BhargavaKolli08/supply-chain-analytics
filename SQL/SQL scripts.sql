-- DIM_CUSTOMER: one row per customer, using the address/segment from their most
-- recent order (customers can have multiple addresses on file, see check above).
CREATE OR REPLACE TABLE MART.DIM_CUSTOMER AS
SELECT
    CUSTOMER_ID,
    CUSTOMER_FNAME,
    CUSTOMER_LNAME,
    CUSTOMER_EMAIL,
    CUSTOMER_SEGMENT,
    CUSTOMER_STREET,
    CUSTOMER_CITY,
    CUSTOMER_STATE,
    CUSTOMER_ZIPCODE,
    CUSTOMER_COUNTRY
FROM (
    SELECT
        CUSTOMER_ID, CUSTOMER_FNAME, CUSTOMER_LNAME, CUSTOMER_EMAIL, CUSTOMER_SEGMENT,
        CUSTOMER_STREET, CUSTOMER_CITY, CUSTOMER_STATE, CUSTOMER_ZIPCODE, CUSTOMER_COUNTRY,
        ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY ORDER_DATE DESC) AS RN
    FROM TRANSFORMED.STG_ORDERS
)
WHERE RN = 1;

-- DIM_PRODUCT: one row per product (PRODUCT_CARD_ID, now fixed above), latest
-- known attributes (catalog price/name are effectively static in this dataset).
CREATE OR REPLACE TABLE MART.DIM_PRODUCT AS
SELECT
    PRODUCT_CARD_ID,
    PRODUCT_NAME,
    PRODUCT_PRICE,
    PRODUCT_IMAGE,
    CATEGORY_ID,
    CATEGORY_NAME,
    DEPARTMENT_ID,
    DEPARTMENT_NAME
FROM (
    SELECT
        PRODUCT_CARD_ID, PRODUCT_NAME, PRODUCT_PRICE, PRODUCT_IMAGE,
        CATEGORY_ID, CATEGORY_NAME, DEPARTMENT_ID, DEPARTMENT_NAME,
        ROW_NUMBER() OVER (PARTITION BY PRODUCT_CARD_ID ORDER BY ORDER_DATE DESC) AS RN
    FROM TRANSFORMED.STG_ORDERS
    WHERE PRODUCT_CARD_ID IS NOT NULL
)
WHERE RN = 1;

-- DIM_GEOGRAPHY: distinct order destinations (market/region/country/state/city).
-- Surrogate key is a deterministic hash so it can be recomputed identically in the fact table.
CREATE OR REPLACE TABLE MART.DIM_GEOGRAPHY AS
SELECT DISTINCT
    HASH(MARKET, ORDER_REGION, ORDER_COUNTRY, ORDER_STATE, ORDER_CITY) AS GEOGRAPHY_KEY,
    MARKET,
    ORDER_REGION,
    ORDER_COUNTRY,
    ORDER_STATE,
    ORDER_CITY
FROM TRANSFORMED.STG_ORDERS;

-- DIM_DATE: calendar dimension spanning the full order/shipping date range.
-- Used as a role-playing dimension: FACT_ORDERS.ORDER_DATE_KEY and .SHIP_DATE_KEY
-- both join to DIM_DATE.DATE_DAY (create two Tableau data source connections, or
-- rename/alias the table, to use it in both roles).
CREATE OR REPLACE TABLE MART.DIM_DATE AS
WITH bounds AS (
    SELECT DATE(MIN(ORDER_DATE)) AS MIN_DATE, DATE(MAX(SHIPPING_DATE)) AS MAX_DATE
    FROM TRANSFORMED.STG_ORDERS
),
days AS (
    SELECT DATEADD(day, SEQ4(), (SELECT MIN_DATE FROM bounds)) AS DATE_DAY
    FROM TABLE(GENERATOR(ROWCOUNT => 5000))
)
SELECT
    DATE_DAY,
    YEAR(DATE_DAY) AS YEAR,
    QUARTER(DATE_DAY) AS QUARTER,
    MONTH(DATE_DAY) AS MONTH,
    MONTHNAME(DATE_DAY) AS MONTH_NAME,
    DAY(DATE_DAY) AS DAY_OF_MONTH,
    DAYOFWEEK(DATE_DAY) AS DAY_OF_WEEK,
    DAYNAME(DATE_DAY) AS DAY_NAME,
    WEEKOFYEAR(DATE_DAY) AS WEEK_OF_YEAR,
    IFF(DAYOFWEEK(DATE_DAY) IN (0, 6), TRUE, FALSE) AS IS_WEEKEND
FROM days
WHERE DATE_DAY <= (SELECT MAX_DATE FROM bounds);

-- FACT_ORDERS: one row per order item, holding measures + FKs to the dims above.
-- SHIPPING_MODE / DELIVERY_STATUS / LATE_DELIVERY_RISK / PAYMENT_TYPE / ORDER_STATUS
-- are kept as degenerate dimensions directly on the fact (low cardinality, no extra
-- attributes of their own, so a separate dim table would just add a pointless join).
CREATE OR REPLACE TABLE MART.FACT_ORDERS AS
SELECT
    ORDER_ITEM_ID,
    ORDER_ID,
    CUSTOMER_ID,
    PRODUCT_CARD_ID,
    HASH(MARKET, ORDER_REGION, ORDER_COUNTRY, ORDER_STATE, ORDER_CITY) AS GEOGRAPHY_KEY,
    DATE(ORDER_DATE) AS ORDER_DATE_KEY,
    DATE(SHIPPING_DATE) AS SHIP_DATE_KEY,
    ORDER_DATE,
    SHIPPING_DATE,
    TYPE AS PAYMENT_TYPE,
    SHIPPING_MODE,
    DELIVERY_STATUS,
    LATE_DELIVERY_RISK,
    ORDER_STATUS,
    ORDER_ITEM_QUANTITY,
    ORDER_ITEM_PRODUCT_PRICE,
    ORDER_ITEM_DISCOUNT,
    ORDER_ITEM_DISCOUNT_RATE,
    SALES,
    ORDER_ITEM_TOTAL,
    ORDER_PROFIT_PER_ORDER,
    BENEFIT_PER_ORDER,
    ORDER_ITEM_PROFIT_RATIO,
    SALES_PER_CUSTOMER,
    DAYS_FOR_SHIPPING_REAL,
    DAYS_FOR_SHIPMENT_SCHEDULED,
    DAYS_BETWEEN_ORDER_AND_SHIP
FROM TRANSFORMED.STG_ORDERS;

